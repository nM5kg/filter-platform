// Person-detector verification harness — Playwright + unpacked extension.
// Usage: node verify-phase2-person.js [block|cover|strict] [extensionDir] [outJson]
//   Defaults: block, ../extension, <extensionDir>/verify/results-person-detector.json
// Loads the extension in a persistent Chromium context (headless), seeds
// ONLY the demo mode via the real popup page (no API token needed — mode
// resolves from fpDemoMode), then:
//   1. runs extension/test-page (same settle logic as verify-phase2.js)
//   2. runs a generated page with the scanner's 16-photo labeled test set
//      (scanner/testset/testset-page.html, generated here from manifest.json)
//      and computes precision/recall vs ground truth, same conventions as
//      scanner/testset/TESTSET.md (uncertain counts as FN for recall, but
//      is reported separately as "covered, safe" vs "missed to ALLOW")
//   3. audits EVERY request the pages + the detector iframe made and
//      flags anything outside the expected set (local test servers,
//      chrome-extension:// files, the page's own cross-origin test images)
//      — the detector must never fetch anything except bundled extension
//      files, and no image data may leave the browser.
// No GitHub upload, no API token, no live internet needed (everything is
// local except the test page's own two cross-origin <img> tags, which are
// expected and recorded, not fetched by the extension).

const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const EXT = path.resolve(process.argv[3] || path.join(ROOT, 'extension'));
const OUT = process.argv[4] || path.join(EXT, 'verify', 'results-person-detector.json');
const TEST_PAGE = path.join(ROOT, 'extension', 'test-page');
const TESTSET_DIR = path.join(ROOT, 'scanner', 'testset');
const MODE = process.argv[2] || 'block';
const CHROME = '/home/hatch/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome';

const sleep = (ms) => new Promise(r => setTimeout(r, ms));

function generateTestsetPage() {
  const manifest = JSON.parse(fs.readFileSync(path.join(TESTSET_DIR, 'manifest.json'), 'utf8'));
  const rows = manifest.images.map(im =>
    `  <figure><img id="${im.id}" data-expect="${im.person_present ? 'human' : 'no-human'}" src="${im.file}" alt="${im.id}"><figcaption>${im.id} — ${im.person_present ? 'מענטש' : 'קיין מענטש'} (${im.category})</figcaption></figure>`
  ).join('\n');
  const html = `<!DOCTYPE html>
<!-- GENERATED by harness/verify-phase2-person.js from manifest.json — do not hand-edit. -->
<html lang="yi" dir="rtl"><head><meta charset="utf-8"><title>טעסט־זאַץ — 16 בילדער</title>
<style>body{font-family:system-ui,sans-serif;max-width:1000px;margin:0 auto;padding:20px} .grid{display:flex;flex-wrap:wrap;gap:16px} figure{margin:0;width:280px} figure img{width:280px;height:210px;object-fit:cover;border:1px solid #ccc} figcaption{font-size:13px;color:#444}</style></head>
<body><h1>טעסט־זאַץ (16 בילדער, ground truth פֿון manifest.json)</h1>
<div class="grid">
${rows}
</div></body></html>
`;
  fs.writeFileSync(path.join(TESTSET_DIR, 'testset-page.html'), html);
  return manifest;
}

async function waitFor(pred, timeoutMs, label) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    try { if (await pred()) return true; } catch (e) { /* keep waiting */ }
    await sleep(500);
  }
  console.log('TIMEOUT waiting for:', label);
  return false;
}

async function findExtensionId(context) {
  const probePage = await context.newPage();
  let extId = null;
  await waitFor(async () => {
    const cdp = await context.newCDPSession(probePage);
    const t = await cdp.send('Target.getTargets');
    const sws = (t.targetInfos || []).filter(x => x.type === 'service_worker' && x.url.includes('chrome-extension://') && x.url.endsWith('/background.js'));
    for (const sw of sws) {
      const id = sw.url.split('/')[2];
      const p = await context.newPage().catch(() => null);
      if (!p) continue;
      try {
        await p.goto(`chrome-extension://${id}/popup.html`, { timeout: 8000 });
        const txt = await p.evaluate(() => document.body.innerText.slice(0, 200)).catch(() => '');
        if (txt.includes('פֿילטער')) { extId = id; await p.close().catch(() => {}); return true; }
      } catch (e) { /* not ours */ }
      await p.close().catch(() => {});
    }
    return false;
  }, 60000, 'extension service worker target');
  return extId;
}

function classifyRequest(url) {
  if (url.startsWith('http://127.0.0.1:8123/') || url.startsWith('http://127.0.0.1:8124/') || url.startsWith('http://127.0.0.1:8125/')) return 'local-test-server';
  if (url.startsWith('chrome-extension://')) return 'extension-file';
  if (url.startsWith('https://commons.wikimedia.org/wiki/Special:FilePath/')) return 'page-xorigin-img';
  if (url === 'https://www.facebook.com/favicon.ico') return 'page-dnr-probe';
  return 'UNEXPECTED';
}

(async () => {
  const manifest = generateTestsetPage();
  const truth = {};
  for (const im of manifest.images) truth[im.file] = im.person_present;
  const result = { mode: MODE, extDir: EXT, ok: false, startedAt: new Date().toISOString() };
  const allRequests = [];
  const profile = path.join('/tmp', 'fp-person-profile-' + MODE);
  fs.rmSync(profile, { recursive: true, force: true });

  const servers = [
    spawn('python3', ['-m', 'http.server', '8123', '--bind', '127.0.0.1'], { cwd: TEST_PAGE, stdio: ['ignore', 'pipe', 'pipe'] }),
    spawn('python3', ['-m', 'http.server', '8124', '--bind', '127.0.0.1'], { cwd: path.join(TEST_PAGE, 'photos'), stdio: ['ignore', 'pipe', 'pipe'] }),
    spawn('python3', ['-m', 'http.server', '8125', '--bind', '127.0.0.1'], { cwd: TESTSET_DIR, stdio: ['ignore', 'pipe', 'pipe'] }),
  ];
  await sleep(1200);

  const context = await chromium.launchPersistentContext(profile, {
    headless: true,
    timeout: 60000,
    executablePath: CHROME,
    ignoreDefaultArgs: ['--disable-extensions', '--disable-component-extensions-with-background-pages'],
    args: [`--load-extension=${EXT}`, '--no-sandbox', '--disable-dev-shm-usage', '--enable-unsafe-swiftshader'],
  });

  try {
    const extId = await findExtensionId(context);
    console.log('extension id:', extId);
    result.extensionId = extId;
    if (!extId) throw new Error('Extension service worker never appeared — extension did not load.');

    // Seed ONLY the demo mode through the real popup page (no API token).
    const popup = await context.newPage();
    await popup.goto(`chrome-extension://${extId}/popup.html`, { timeout: 20000 });
    await popup.evaluate(async (demoMode) => {
      await chrome.storage.local.clear();
      await chrome.storage.local.set({ fpDemoMode: demoMode });
    }, MODE);
    await popup.close();

    const page = await context.newPage();
    page.on('console', m => { if (m.text().includes('[fp]') || m.text().includes('[fp-detector]')) console.log('  page console:', m.text().slice(0, 250)); });
    page.on('pageerror', e => console.log('  page error:', String(e).slice(0, 300)));
    page.on('request', r => allRequests.push({ url: r.url(), method: r.method(), type: r.resourceType(), cls: classifyRequest(r.url()) }));
    page.on('requestfailed', r => console.log('  request failed:', r.url().slice(0, 120), (r.failure() && r.failure().errorText) || '?'));

    const readDom = () => page.evaluate(() => {
      const raw = document.getElementById('fp-dom-stats');
      const parsed = raw ? JSON.parse(raw.textContent) : null;
      return {
        stats: parsed ? parsed.stats : null,
        personReady: parsed ? parsed.personReady : null,
        log: parsed ? parsed.log : [],
        mode: document.documentElement.getAttribute('data-fp-mode'),
        personReadyAttr: document.documentElement.getAttribute('data-fp-person-ready'),
        blockedPlaceholders: document.querySelectorAll('[data-fp-blocked]').length,
        coveredImgs: document.querySelectorAll('[data-fp-covered]').length,
        imgStates: Array.from(document.querySelectorAll('img')).map(i => ({ id: i.id, action: i.dataset.fpAction || 'none' })),
        bgBlocked: document.querySelectorAll('[data-fp-bg-blocked]').length,
        bgCoverOverlays: document.querySelectorAll('.fp-bg-cover').length,
      };
    });

    // ---- 1. extension test page ----
    console.log('\n===== TEST PAGE (mode ' + MODE + ') =====');
    let navStart = Date.now();
    await page.goto('http://127.0.0.1:8123/index.html', { waitUntil: 'load', timeout: 30000 });
    const modelReady = await waitFor(async () => page.evaluate(() => document.documentElement.getAttribute('data-fp-model-ready') === 'true'), 120000, 'model load');
    const modelReadyMs = Date.now() - navStart;
    const scanDone = await waitFor(async () => page.evaluate(() => document.documentElement.getAttribute('data-fp-scan-done') === 'true'), 300000, 'first scan');
    const scanMs = Date.now() - navStart;
    console.log('model ready:', modelReady, `(${modelReadyMs} ms)`, '| scan done:', scanDone, `(${scanMs} ms)`);
    await sleep(3500);
    await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
    await sleep(1500);
    await page.evaluate(() => window.scrollTo(0, 0));
    await waitFor(async () => page.evaluate(() => {
      const raw = document.getElementById('fp-dom-stats');
      if (!raw) return false;
      const l = JSON.parse(raw.textContent).log;
      return l.filter(e => e.src.includes('person-marie-curie')).length >= 2
        && l.filter(e => e.src.includes('person-obama-family')).length >= 2;
    }), 180000, 'dynamic+lazy processed');
    await sleep(1500);
    const tp = await readDom();
    result.testPage = { ...tp, modelReadyMs, scanMs, scanDone, modelReady };
    console.log('mode on page:', tp.mode, '| personReady:', tp.personReadyAttr);
    console.log('stats:', JSON.stringify(tp.stats));
    console.log('img states:', JSON.stringify(tp.imgStates));
    console.log('bg blocked:', tp.bgBlocked, 'bg covered:', tp.bgCoverOverlays);
    for (const e of tp.log) console.log('  log:', JSON.stringify(e));
    await page.screenshot({ path: path.join(path.dirname(OUT), MODE + '-person-mode.png'), fullPage: true }).catch(() => {});

    // ---- 2. labeled 16-photo test set ----
    console.log('\n===== TEST SET (16 photos) =====');
    navStart = Date.now();
    await page.goto('http://127.0.0.1:8125/testset-page.html', { waitUntil: 'load', timeout: 30000 });
    const tsModelReady = await waitFor(async () => page.evaluate(() => document.documentElement.getAttribute('data-fp-model-ready') === 'true'), 120000, 'testset model load');
    const tsModelReadyMs = Date.now() - navStart;
    const tsScanDone = await waitFor(async () => page.evaluate(() => document.documentElement.getAttribute('data-fp-scan-done') === 'true'), 300000, 'testset scan');
    const tsScanMs = Date.now() - navStart;
    await sleep(2000);
    const ts = await readDom();
    console.log('model ready:', tsModelReady, `(${tsModelReadyMs} ms)`, '| scan done:', tsScanDone, `(${tsScanMs} ms)`);
    console.log('stats:', JSON.stringify(ts.stats));
    console.log('personReady:', ts.personReadyAttr);

    // Per-image verdicts, joined with ground truth by filename.
    const byFile = {};
    for (const e of ts.log) {
      if (e.kind !== 'img') continue;
      const file = decodeURIComponent(e.src.split('/').pop().split('?')[0]);
      byFile[file] = e; // last entry wins (each image scanned once here)
    }
    const perImage = [];
    let tpN = 0, fpN = 0, fnN = 0, tnN = 0, uncertainPerson = 0, missedToAllow = 0, missing = 0;
    for (const im of manifest.images) {
      const e = byFile[im.file];
      if (!e) { missing++; perImage.push({ id: im.id, file: im.file, truth: im.person_present, verdict: 'MISSING' }); continue; }
      const verdict = e.result; // human | uncertain | no-human
      const isPos = verdict === 'human';
      if (im.person_present && isPos) tpN++;
      else if (!im.person_present && isPos) fpN++;
      else if (im.person_present && !isPos) { fnN++; if (verdict === 'uncertain') uncertainPerson++; else missedToAllow++; }
      else tnN++;
      perImage.push({
        id: im.id, file: im.file, truth: im.person_present, verdict,
        persons: e.persons, personBest: e.personBest, faces: e.faces, faceBest: e.faceBest,
        detectedBy: e.detectedBy, ms: e.ms, action: e.action,
      });
    }
    const precision = tpN + fpN ? +(tpN / (tpN + fpN)).toFixed(3) : null;
    const recall = tpN + fnN ? +(tpN / (tpN + fnN)).toFixed(3) : null;
    const detectMss = perImage.filter(p => p.ms).map(p => p.ms).sort((a, b) => a - b);
    const meanMs = detectMss.length ? Math.round(detectMss.reduce((a, b) => a + b, 0) / detectMss.length) : null;
    const medianMs = detectMss.length ? detectMss[Math.floor(detectMss.length / 2)] : null;
    const metrics = {
      n: 16, tp: tpN, fp: fpN, fn: fnN, tn: tnN, precision, recall,
      uncertainPersonImages: uncertainPerson, missedToAllow, missing,
      meanDetectMs: meanMs, medianDetectMs: medianMs,
      testsetScanMs: tsScanMs, testsetModelReadyMs: tsModelReadyMs,
    };
    result.testset = { metrics, perImage, stats: ts.stats, personReady: ts.personReadyAttr };
    console.log('metrics:', JSON.stringify(metrics));
    for (const p of perImage) console.log('  img:', JSON.stringify(p));

    // ---- 3. exfiltration audit ----
    const byClass = {};
    for (const r of allRequests) byClass[r.cls] = (byClass[r.cls] || 0) + 1;
    const unexpected = allRequests.filter(r => r.cls === 'UNEXPECTED');
    const nonGet = allRequests.filter(r => r.method !== 'GET');
    const extRequests = allRequests.filter(r => r.cls === 'extension-file');
    result.requests = { total: allRequests.length, byClass, unexpected, nonGet: nonGet.map(r => r.url), extensionRequests: extRequests.length };
    console.log('\nrequests total:', allRequests.length, 'by class:', JSON.stringify(byClass));
    console.log('extension-file requests:', extRequests.length, extRequests.slice(0, 12).map(r => r.url.replace(/^chrome-extension:\/\/[^/]+/, 'chrome-extension://<id>')));
    console.log('UNEXPECTED requests:', JSON.stringify(unexpected));
    console.log('non-GET requests:', JSON.stringify(nonGet.map(r => r.url)));
    result.ok = true;
  } catch (e) {
    result.error = String(e && e.stack ? e.stack : e).slice(0, 2000);
    console.log('RUN ERROR:', result.error);
  } finally {
    await context.close().catch(() => {});
    for (const s of servers) s.kill();
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, JSON.stringify(result, null, 2));
  console.log('\nResults saved to', OUT);
  console.log(JSON.stringify({
    mode: result.mode, ok: result.ok,
    testPageStats: result.testPage && result.testPage.stats,
    testsetMetrics: result.testset && result.testset.metrics,
    requests: result.requests && result.requests.byClass,
    unexpected: result.requests && result.requests.unexpected.length,
  }, null, 2));
})().catch(e => { console.error(e); process.exit(1); });
